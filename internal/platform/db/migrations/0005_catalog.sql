-- 0005_catalog.sql
--
-- Backing tables for internal/modules/catalog's two aggregates (Product
-- and Recipe, plus their ProductIngredient/RecipeIngredient value-object
-- lines), as persisted by internal/modules/catalog/infrastructure/postgres.
-- Follows the same ownership/RLS convention as 0001/0002/0003/0004/0006:
-- every table is owned by whichever administrative role runs migrations
-- (never mesaposta_app), RLS is enabled AND forced, and every policy is
-- named "tenant_isolation" with the exact same predicate used since
-- 0001_baseline.sql:
--
--     USING (tenant_id = current_setting('app.tenant_id', true)::uuid)
--     WITH CHECK (tenant_id = current_setting('app.tenant_id', true)::uuid)
--
-- Cross-tenant foreign keys: both parent tables (products, recipes)
-- additionally carry a UNIQUE (tenant_id, id) constraint, and every child
-- table's foreign key is composite -- FOREIGN KEY (tenant_id, <col>)
-- REFERENCES <parent> (tenant_id, id) -- instead of a bare
-- FOREIGN KEY (<col>) REFERENCES <parent> (id), for the identical reason
-- documented in 0004_operations.sql: a single-column FK would let a row
-- reference a same-"id" row belonging to a DIFFERENT tenant.
--
-- ingredient_id (on both product_ingredients and recipe_ingredients)
-- carries NO foreign key: it references a StockItem owned by the
-- operations module (internal/modules/operations), and this phase's scope
-- explicitly excludes any cross-module integration (see BACKLOG.md) --
-- mirroring 0004_operations.sql's own stock_items.supplier_id column,
-- which documents the identical "no FK yet" decision for the same reason.
--
-- Monetary columns are numeric(14,2) (whole currency units, 2 decimal
-- places); quantity columns are numeric(14,3) (whole units, 3 decimal
-- places) -- the exact same scale/convention 0004_operations.sql
-- establishes for domain.Money/domain.Quantity. discount_percent is
-- numeric(5,2) (0.00-100.00), matching
-- internal/modules/catalog/domain.DiscountPercent's own hundredths-of-a-
-- percent fixed-point scale: the Postgres adapter converts between the
-- integer and numeric representations inline in its SQL, exactly like it
-- already does for Money/Quantity ("$n::numeric / 100" / "$n::numeric / 1000"
-- on the way in, "(column * 100)::bigint" / "(column * 1000)::bigint" on
-- the way out).
--
-- products.version supports optimistic concurrency (see
-- internal/modules/catalog/domain/ports.go's ProductRepository.UpdateWithVersion
-- doc comment): Product is the only mutable aggregate in this module
-- (ApplyDiscount is its sole post-creation mutation). recipes.version
-- exists for schema symmetry/future-proofing but this phase's
-- RecipeRepository never issues an UPDATE against it (see
-- domain/recipe.go's own doc comment on why Recipe has no mutation use
-- case yet).

-- +goose Up

-- products: a sellable item in a tenant's catalog (see domain/product.go).
-- is_active defaults to true, matching Product's own "a freshly created
-- product always starts active" invariant (NewProduct).
CREATE TABLE products (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL,
    name text NOT NULL,
    description text NOT NULL,
    base_price numeric(14,2) NOT NULL CHECK (base_price > 0),
    discount_percent numeric(5,2) NULL CHECK (discount_percent >= 0 AND discount_percent <= 100),
    is_active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT products_tenant_id_id_key UNIQUE (tenant_id, id)
);

ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE products FORCE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON products
    USING (tenant_id = current_setting('app.tenant_id', true)::uuid)
    WITH CHECK (tenant_id = current_setting('app.tenant_id', true)::uuid);

GRANT SELECT, INSERT, UPDATE, DELETE ON products TO mesaposta_app;

-- product_ingredients: ProductIngredient, a value object with no identity
-- of its own outside the Product that owns it (see domain/product.go) --
-- hence the surrogate "id" primary key (needed for the row to have one at
-- all) is never read back by application code, only ever generated by the
-- database default. UNIQUE (tenant_id, product_id, ingredient_id) is the
-- physical mirror of NewProduct's own in-memory invariant that no two
-- ingredient lines on the same product may reference the same ingredient.
--
-- Like purchase_order_items in 0004_operations.sql, this table is never
-- updated after insert (Product.Ingredients() never changes once the
-- product is created -- ApplyDiscount only ever touches
-- discount_percent/version/updated_at), so it is granted SELECT and
-- INSERT only.
CREATE TABLE product_ingredients (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid NOT NULL,
    product_id uuid NOT NULL,
    ingredient_id uuid NOT NULL, -- no FK: references operations.stock_items, out of scope this phase.
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    CONSTRAINT product_ingredients_product_fk
        FOREIGN KEY (tenant_id, product_id) REFERENCES products (tenant_id, id),
    CONSTRAINT product_ingredients_tenant_product_ingredient_key UNIQUE (tenant_id, product_id, ingredient_id)
);

ALTER TABLE product_ingredients ENABLE ROW LEVEL SECURITY;
ALTER TABLE product_ingredients FORCE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON product_ingredients
    USING (tenant_id = current_setting('app.tenant_id', true)::uuid)
    WITH CHECK (tenant_id = current_setting('app.tenant_id', true)::uuid);

GRANT SELECT, INSERT ON product_ingredients TO mesaposta_app;

-- recipes: a preparation template that can later be promoted into a
-- sellable Product (see domain/recipe.go).
