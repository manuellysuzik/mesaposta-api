-- recipe_ingredients: RecipeIngredient, a value object with no identity of
-- its own outside the Recipe that owns it (see domain/recipe.go). Unlike
-- product_ingredients, a Recipe's ingredient list DOES change in-memory
-- across the aggregate's lifetime in principle (NewRecipe allows an empty,
-- still-being-composed draft -- see that constructor's doc comment), but
-- this phase ships no "edit recipe ingredients" use case, so, exactly like
-- product_ingredients, this table is only ever inserted into, never
-- updated -- granted SELECT and INSERT only.
CREATE TABLE recipe_ingredients (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid NOT NULL,
    recipe_id uuid NOT NULL,
    ingredient_id uuid NOT NULL, -- no FK: references operations.stock_items, out of scope this phase.
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    CONSTRAINT recipe_ingredients_recipe_fk
        FOREIGN KEY (tenant_id, recipe_id) REFERENCES recipes (tenant_id, id),
    CONSTRAINT recipe_ingredients_tenant_recipe_ingredient_key UNIQUE (tenant_id, recipe_id, ingredient_id)
);

