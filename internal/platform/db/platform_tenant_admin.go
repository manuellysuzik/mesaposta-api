package db

import (
	"context"
	"errors"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"

	"github.com/manuellysuzik/mesaposta-api/internal/platform/errs"
)

// platformTenantUniqueViolationCode is the Postgres error code for a
// unique-constraint violation (SQLSTATE 23505) -- duplicated per package
// rather than shared, mirroring every other module's own
// isUniqueViolation/uniqueViolationCode pair (e.g.
// internal/modules/crm/infrastructure/postgres/customer_repository.go).
const platformTenantUniqueViolationCode = "23505"

// isPlatformTenantUniqueViolation reports whether err is a Postgres
// unique-constraint violation.
func isPlatformTenantUniqueViolation(err error) bool {
	var pgErr *pgconn.PgError
	return errors.As(err, &pgErr) && pgErr.Code == platformTenantUniqueViolationCode
}

// platformTenantInvalidTextRepresentationCode is the Postgres error code
// (SQLSTATE 22P02) returned when a query parameter cannot even be parsed
// as its target column's type -- in particular, a path-supplied tenant id
// that isn't syntactically a UUID at all.
const platformTenantInvalidTextRepresentationCode = "22P02"

// isPlatformTenantInvalidIDFormat reports whether err is Postgres rejecting
// a malformed UUID literal.
func isPlatformTenantInvalidIDFormat(err error) bool {
	var pgErr *pgconn.PgError
	return errors.As(err, &pgErr) && pgErr.Code == platformTenantInvalidTextRepresentationCode
}

// platformTenantColumns is the exact column list/order every query below
// selects or RETURNINGs, and therefore the exact order scanPlatformTenant
// expects.
const platformTenantColumns = `id, slug, name, owner_name, owner_email, phone, plan, status, is_active, created_at`

// PlatformTenant is the raw row shape every platform tenant administration
// query below returns. Every field mirrors a tenants column as-is (see
// 0008_tenants.sql, extended by 0012_tenants_platform_fields.sql) --
// converting these into any caller-facing HTTP response shape is
// internal/platform/platformadmin/http's job, exactly as
// UserCredentials/LookupTenantBySlug's raw string return values are their
// own callers' job to convert, never this package's.
type PlatformTenant struct {
	ID         string
	Slug       string
	Name       string
	OwnerName  *string
	OwnerEmail *string
	Phone      *string
	Plan       string
	Status     string
	IsActive   bool
	CreatedAt  time.Time
}

// rowScanner is the subset of pgx.Row/pgx.Rows this file's queries need to
// read a single PlatformTenant row from -- satisfied by both, so
// scanPlatformTenant can back every method below (QueryRow-based or
// Query-based) with one implementation.
type rowScanner interface {
	Scan(dest ...any) error
}

// scanPlatformTenant reads one row -- in platformTenantColumns' exact
// order -- into a PlatformTenant.
func scanPlatformTenant(row rowScanner) (PlatformTenant, error) {
	var t PlatformTenant
	err := row.Scan(&t.ID, &t.Slug, &t.Name, &t.OwnerName, &t.OwnerEmail, &t.Phone, &t.Plan, &t.Status, &t.IsActive, &t.CreatedAt)
	return t, err
}

// tenantNotFoundErr builds the *errs.Error UpdateTenantDetails/
// SetTenantStatus return when id does not match any row.
func tenantNotFoundErr(cause error) error {
	return errs.New(errs.NotFound, "tenant_not_found", "tenant not found", cause)
}

// tenantSlugTakenErr builds the *errs.Error CreateTenant returns when slug
// collides with an existing tenant's unique slug.
func tenantSlugTakenErr(cause error) error {
	return errs.New(errs.Conflict, "tenant_slug_taken", "a tenant with this slug already exists", cause)
}

// isActiveForStatus derives the tenants.is_active column from status,
// rather than letting a caller set the two independently: SetTenantStatus
// is the only place this codebase ever writes is_active for an existing
// tenant, so there is exactly one place this derivation can ever drift.
// Deliberately allow-list shaped (only "trial"/"active" are active) rather
// than deny-list shaped, so an unrecognized future status value defaults
// to inactive -- the safer failure mode for the public, slug-addressed
// menu routes internal/platform/db.Pool.LookupTenantBySlug gates on this
// column.
func isActiveForStatus(status string) bool {
	switch status {
	case "trial", "active":
		return true
	default:
		return false
	}
}

// CreateTenantInput is CreateTenant's input. Status is deliberately absent:
// a newly created tenant always starts as "trial" -- this is a business
// invariant enforced here in SQL, not something a caller chooses.
type CreateTenantInput struct {
	// ID is the new tenant's UUID, generated by the caller (mirroring
	// cmd/seedtenant's own convention of generating an id before ever
	// reaching this package, since id generation needs no database
	// round-trip and has no business belonging in this data-access layer).
	ID         string
	Slug       string
	Name       string
	OwnerName  *string
	OwnerEmail *string
	Phone      *string
	Plan       string
}

const createTenantSQL = `
	INSERT INTO tenants (id, slug, name, owner_name, owner_email, phone, plan, status, is_active, created_at)
	VALUES ($1, $2, $3, $4, $5, $6, $7, 'trial', true, now())
	RETURNING ` + platformTenantColumns

// CreateTenant inserts a new tenant row, always starting in "trial" status
// with is_active=true.
//
// THIRD deliberate exception to this package's core invariant that no
// query ever runs outside a tenant-scoped Pool.Scope (see
// LookupTenantBySlug and LookupUserCredentialsByEmail's own doc comments
// for the first two) -- but a categorically different one from those: both
// of those exist to bootstrap tenant identity BEFORE a tenant is
// established in the request, for an otherwise ordinary tenant-scoped
// caller. CreateTenant (and ListTenants/UpdateTenantDetails/
// SetTenantStatus below) can never run inside a tenant Scope at all,
// because they ARE the mechanism that creates/manages tenants themselves --
// there is no tenant_id to scope by, on purpose, for the exact same reason
// 0008_tenants.sql's own header comment gives for why tenants carries no
// "tenant_isolation" RLS policy. Authorization for this category is
// enforced entirely by internal/platform/platformadmin.RequireToken at the
// HTTP layer, never by Scope/RLS.
func (p *Pool) CreateTenant(ctx context.Context, input CreateTenantInput) (PlatformTenant, error) {
	row := p.pool.QueryRow(ctx, createTenantSQL,
		input.ID, input.Slug, input.Name, input.OwnerName, input.OwnerEmail, input.Phone, input.Plan)
	t, err := scanPlatformTenant(row)
	if err != nil {
		if isPlatformTenantUniqueViolation(err) {
			return PlatformTenant{}, tenantSlugTakenErr(err)
		}
		return PlatformTenant{}, errs.New(errs.Internal, "tenant_create_failed", "failed to create tenant", err)
	}
	return t, nil
}

const listTenantsSQL = `SELECT ` + platformTenantColumns + ` FROM tenants ORDER BY created_at DESC`

// ListTenants returns every tenant on the platform, newest first. See
// CreateTenant's own doc comment for why this bypasses Scope entirely --
// listing every tenant is inherently a cross-tenant, platform-level
// operation, not a per-tenant one.
func (p *Pool) ListTenants(ctx context.Context) ([]PlatformTenant, error) {
	rows, err := p.pool.Query(ctx, listTenantsSQL)
	if err != nil {
		return nil, errs.New(errs.Internal, "tenant_list_failed", "failed to list tenants", err)
	}
	defer rows.Close()

	var out []PlatformTenant
	for rows.Next() {
		t, err := scanPlatformTenant(rows)
		if err != nil {
			return nil, errs.New(errs.Internal, "tenant_list_failed", "failed to list tenants", err)
		}
		out = append(out, t)
	}
	if err := rows.Err(); err != nil {
		return nil, errs.New(errs.Internal, "tenant_list_failed", "failed to list tenants", err)
	}
	return out, nil
}

// UpdateTenantDetailsInput is UpdateTenantDetails' input. Slug is
// deliberately absent: /public/v1/{tenantSlug}/... routes embed a tenant's
// slug directly in URLs a diner may have bookmarked/shared, so it is
// immutable after creation. Status/IsActive are also absent -- those are
// SetTenantStatus's job, kept as a separate, narrower operation rather than
// folded into a single "update everything" call, mirroring this codebase's
// existing convention of narrow, named actions (e.g.
// internal/modules/ordering's own ativar/desativar) over a generic
// PATCH-shaped update.
//
// Every field here is a full REPLACE, not a partial patch: UpdateTenant
// Details always overwrites OwnerName/OwnerEmail/Phone/Plan/Name with
// exactly what is passed, including setting a pointer field to NULL if it
// is nil. This mirrors mesaposta-frontend's own tenant-form-dialog.tsx,
// which always submits every field of its form on every save -- a caller
// that wants to preserve an existing value must resend it, not omit it.
type UpdateTenantDetailsInput struct {
	Name       string
	OwnerName  *string
	OwnerEmail *string
	Phone      *string
	Plan       string
}

const updateTenantDetailsSQL = `
	UPDATE tenants
	SET name = $2, owner_name = $3, owner_email = $4, phone = $5, plan = $6
	WHERE id = $1
	RETURNING ` + platformTenantColumns

// UpdateTenantDetails updates a tenant's editable, non-status fields. See
// CreateTenant's own doc comment for why this bypasses Scope.
func (p *Pool) UpdateTenantDetails(ctx context.Context, id string, input UpdateTenantDetailsInput) (PlatformTenant, error) {
	row := p.pool.QueryRow(ctx, updateTenantDetailsSQL,
		id, input.Name, input.OwnerName, input.OwnerEmail, input.Phone, input.Plan)
	t, err := scanPlatformTenant(row)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) || isPlatformTenantInvalidIDFormat(err) {
			return PlatformTenant{}, tenantNotFoundErr(err)
		}
		return PlatformTenant{}, errs.New(errs.Internal, "tenant_update_failed", "failed to update tenant", err)
	}
	return t, nil
}

const setTenantStatusSQL = `
	UPDATE tenants
	SET status = $2, is_active = $3
	WHERE id = $1
	RETURNING ` + platformTenantColumns

// SetTenantStatus transitions a tenant to status, deriving is_active from
// it via isActiveForStatus in the same statement -- the only place this
// codebase ever writes tenants.is_active for a row that already exists.
// See CreateTenant's own doc comment for why this bypasses Scope. status is
// expected to already be validated against the closed set
// internal/platform/platformadmin/http's DTO layer enforces (mirroring
// every other module's own "validate at the HTTP boundary, trust internal
// callers" convention) -- the tenants_status_check CHECK constraint
// (0012_tenants_platform_fields.sql) is this call's last line of defense,
// not its primary one.
func (p *Pool) SetTenantStatus(ctx context.Context, id, status string) (PlatformTenant, error) {
	row := p.pool.QueryRow(ctx, setTenantStatusSQL, id, status, isActiveForStatus(status))
	t, err := scanPlatformTenant(row)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) || isPlatformTenantInvalidIDFormat(err) {
			return PlatformTenant{}, tenantNotFoundErr(err)
		}
		return PlatformTenant{}, errs.New(errs.Internal, "tenant_status_update_failed", "failed to update tenant status", err)
	}
	return t, nil
}
